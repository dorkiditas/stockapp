def execution_gap(prices=None):
    """在案未执行的卖出 call:不执行到今天赚了还是亏了。
    正数 = 拖延反而占了便宜;负数 = 拖延吃了亏。**都不改变 call 本身对不对。**"""
    px = prices or dict((c, p) for c, _s, p, *_ in POSITIONS)
    rows, tot, tot_price = [], 0.0, 0.0
    for code, act, day, sh, p0, kind, why in OPEN_CALLS:
        p1 = px.get(code)
        if p1 is None:
            continue
        delta = sh * (p1 - p0)
        tot += delta
        if kind == "price":
            tot_price += delta
        rows.append({"代码": code, "在案动作": act, "下达日": day, "股数": sh,
                     "下达价": p0, "现价": p1, "未执行盈亏": delta,
                     "类型": "风险预算" if kind == "risk" else "价格判断", "理由": why})
    return rows, tot, tot_price


