def load_account():
    """实盘账户优先,没有就用本文件快照。返回 (dict, 来源说明)。"""
    if os.path.exists(RISK):
        try:
            a = json.load(open(RISK, encoding="utf-8"))
            if a.get("net_liquidation"):
                return a, "account_risk.json(实盘)"
        except Exception:
            pass
    return SNAPSHOT, f"heavy.py 快照({ASOF})"


def positions():
    """返回逐仓明细 list[dict],按 |市值| 降序。"""
    acct, _ = load_account()
    nlv = float(acct["net_liquidation"])
    gross = float(acct["gross_position_value"])
    out = []
    for code, sh, px, cost, unreal, daily in POSITIONS:
        mv = sh * px
        basis = abs(cost * sh)
        out.append({
            "代码": code, "股数": sh, "现价": px, "成本": cost,
            "市值": mv, "浮动盈亏": unreal,
            "浮动%": (unreal / basis * 100) if basis else None,
            "上日盈亏": daily,
            "%净值": mv / nlv * 100,
            "%gross": abs(mv) / gross * 100,
            "重仓": abs(mv) / nlv >= HEAVY_THRESHOLD,
        })
    out.sort(key=lambda r: -abs(r["市值"]))
    return out


def concentration():
    """集中度:top3 / top5 / 因子簇 / 死钱,全部以净值为分母。"""
    acct, _ = load_account()
    nlv = float(acct["net_liquidation"])
    mv = {c: sh * px for c, sh, px, *_ in POSITIONS}
    pick = lambda *cs: sum(abs(mv.get(c, 0)) for c in cs)
    rank = sorted(mv.items(), key=lambda kv: -abs(kv[1]))
    return {
        "第一大仓": (rank[0][0], rank[0][1], rank[0][1] / nlv * 100),
        "top3": sum(abs(v) for _, v in rank[:3]) / nlv * 100,
        "top5": sum(abs(v) for _, v in rank[:5]) / nlv * 100,
        # 同一个赌注的三种包装:直接股权 + 封闭式基金溢价包装 + 主题ETF
        "太空因子": pick("SPCX", "DXYZ", "NASA") / nlv * 100,
        # 档案里标🔴清理、与 AI edge 无关的三笔
        "死钱三笔": pick("DXYZ", "EWZ", "NASA") / nlv * 100,
        "浮动盈亏合计": sum(u for *_, u, _ in POSITIONS),
    }


def stress():
    """风险数学。两个口径都给:保守(维持保证金不变)与实际(维持保证金同步下降)。"""
    acct, _ = load_account()
    nlv = float(acct["net_liquidation"])
    gross = float(acct["gross_position_value"])
    buf = float(acct["excess_liquidity"])
    mm = float(acct.get("maintenance_margin") or 0)
    mm_rate = mm / gross if gross else 0.30
    return {
        "缓冲": buf,
        "缓冲/净值%": buf / nlv * 100,
        "同步跌归零%_保守": buf / gross * 100,
        # 全书同步跌 p:净值 -gross*p,维持保证金 -gross*p*mm_rate → 缓冲 -gross*p*(1-mm_rate)
        "同步跌归零%_计入保证金释放": (buf / (gross * (1 - mm_rate)) * 100) if gross else None,
        "维持保证金率%": mm_rate * 100,
        "杠杆": float(acct.get("leverage") or gross / nlv),
    }


def single_name_shocks():
    """单票冲击 → 吃掉多少缓冲。3σ 用各票自己的年化历史波动换算单日。"""
    acct, _ = load_account()
    buf = float(acct["excess_liquidity"])
    mv = {c: sh * px for c, sh, px, *_ in POSITIONS}
    rows = []

    def add(label, code, pct):
        hit = mv[code] * pct
        rows.append({"情景": label, "代码": code, "冲击%": pct * 100,
                     "金额": hit, "占缓冲%": abs(hit) / buf * 100})

    for code, (hv, _iv, _hi, lo) in VOL.items():
        if code not in mv:
            continue
        sigma = hv / (252 ** 0.5)
        add(f"{code} 单日 -3σ", code, -3 * sigma)
    if "SPCX" in mv:
        px = dict((c, p) for c, _s, p, *_ in POSITIONS)["SPCX"]
        add("SPCX 回到硬止损 $104.83(=52周低)", "SPCX", (104.83 - px) / px)
    add("AVGO 重演 8/14(-5.81%)", "AVGO", -0.0581)
    add("SIEGY -8% 跳空", "SIEGY", -0.08)
    rows.sort(key=lambda r: -r["占缓冲%"])
    return rows


def execution_gap(prices=None):
    """在案未执行的卖出 call:不执行到今天赚了还是亏了。
    正数 = 拖延反而占了便宜;负数 = 拖延吃了亏。**都不改变 call 本身对不对。**"""
    px = prices or dict((c, p) for c, _s, p, *_ in POSITIONS)
    rows, tot, tot_price = [], 0.0, 0.0
    for code, act, day, sh, p0, kind, why in OPEN_CALLS:
        p1 = px.get(code)
        if p1 is None:
            continue
        delta = sh * (p1 - p0)
        tot += delta
        if kind == "price":
            tot_price += delta
        rows.append({"代码": code, "在案动作": act, "下达日": day, "股数": sh,
                     "下达价": p0, "现价": p1, "未执行盈亏": delta,
                     "类型": "风险预算" if kind == "risk" else "价格判断", "理由": why})
    return rows, tot, tot_price


